"""Measure each engine version against the previous one.

    uv run ladder.py                      # play any pairs not measured yet
    uv run ladder.py --games 400 --redo   # replay every pair

Builds missing versions, plays version N against version N-1 with match.py,
stores the results in ../docs/engine-history.json and rewrites
../docs/engine-history.md: a table of what each version added and how much
Elo it was worth. Versions that only understand `go depth` play at their fixed
depth (see versions.txt); everything else plays on the clock.
"""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

from versions import BIN, ROOT, build, load_manifest

DOCS = ROOT / "docs"
RESULTS = DOCS / "engine-history.json"
TABLE = DOCS / "engine-history.md"
FINAL = re.compile(r"final: \+(\d+) =(\d+) -(\d+)\s+elo ([+-]?[\d.]+|[+-]?inf) ± ([\d.]+|inf)")


def play(new, old, args) -> dict:
    cmd = [sys.executable, str(Path(__file__).with_name("match.py")), str(BIN / new.name), str(BIN / old.name),
           "--games", str(args.games), "--tc", args.tc, "--concurrency", str(args.concurrency),
           "--seed", str(args.seed)]
    if new.depth:
        cmd += ["--depth-a", str(new.depth)]
    if old.depth:
        cmd += ["--depth-b", str(old.depth)]
    print(f"\n== {new.name} vs {old.name}", flush=True)
    out = subprocess.run(cmd, capture_output=True, text=True)
    lines = out.stdout.splitlines()
    for line in lines[-4:]:
        print("  " + line)
    m = next((FINAL.search(l) for l in reversed(lines) if FINAL.search(l)), None)
    if out.returncode != 0 or not m:
        sys.exit(f"match failed:\n{out.stdout[-2000:]}\n{out.stderr[-2000:]}")
    w, d, l = map(int, m.group(1, 2, 3))
    return {"new": new.name, "old": old.name, "commit_new": new.commit, "commit_old": old.commit,
            "w": w, "d": d, "l": l, "elo": float(m.group(4)), "err": float(m.group(5)),
            "tc": args.tc, "games": w + d + l,
            "limits": {new.name: f"depth {new.depth}" if new.depth else args.tc,
                       old.name: f"depth {old.depth}" if old.depth else args.tc}}


def fmt_elo(x: float) -> str:
    return "∞" if x == float("inf") else ("-∞" if x == float("-inf") else f"{x:+.0f}")


def write_table(versions, results):
    by_pair = {(r["new"], r["old"]): r for r in results}
    rows, total, total_known = [], 0.0, True
    for i, v in enumerate(versions):
        if i == 0:
            rows.append(f"| `{v.name}` | {v.description} | baseline | | 0 |")
            continue
        r = by_pair.get((v.name, versions[i - 1].name))
        if r is None:
            total_known = False
            rows.append(f"| `{v.name}` | {v.description} | not measured | | |")
            continue
        total += r["elo"]
        score = f"+{r['w']} ={r['d']} −{r['l']}"
        rows.append(f"| `{v.name}` | {v.description} | **{fmt_elo(r['elo'])}** ± {r['err']:.0f} | {score} | "
                    f"{fmt_elo(total) if total_known else '?'} |")
    limits = sorted({f"`{n}` at {lim}" for r in results for n, lim in r["limits"].items() if lim.startswith("depth")})
    tcs = sorted({r["tc"] for r in results})
    DOCS.mkdir(exist_ok=True)
    TABLE.write_text(f"""# Engine history

Each version played against the one before it (generated by `make ladder`;
do not edit by hand). Elo is with a 95% interval, from {', '.join(tcs) or '?'} games
with paired random openings. "Total" adds the steps up, so it is only a rough
guide: Elo gains are not exactly additive across different opponents.

Versions from before time control was added search to a fixed depth
({', '.join(limits) or 'none'}), so their steps measure the change at that depth.
Build any version with `make versions` and play it with `make play`.

| Version | What it added | Elo vs previous | Score (W/D/L) | Total |
|---|---|---|---|---|
""" + "\n".join(rows) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--games", type=int, default=200)
    ap.add_argument("--tc", default="8+0.08")
    ap.add_argument("--concurrency", type=int, default=4)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--redo", action="store_true", help="replay pairs that already have results")
    args = ap.parse_args()

    versions = load_manifest()
    for v in versions:
        build(v)
    results = json.loads(RESULTS.read_text()) if RESULTS.exists() else []
    for i in range(1, len(versions)):
        new, old = versions[i], versions[i - 1]
        done = [r for r in results if r["new"] == new.name and r["old"] == old.name
                and r["commit_new"] == new.commit and r["commit_old"] == old.commit]
        if done and not args.redo:
            continue
        results = [r for r in results if not (r["new"] == new.name and r["old"] == old.name)]
        results.append(play(new, old, args))
        DOCS.mkdir(exist_ok=True)
        RESULTS.write_text(json.dumps(results, indent=1) + "\n")
        write_table(versions, results)
    write_table(versions, results)
    print(f"\nwrote {TABLE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
